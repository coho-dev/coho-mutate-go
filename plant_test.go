// planted is a mutant as a test reads it: the text it replaces, what it
// puts there, and its kind.
type planted struct {
	was, now, mutator string
}

func plantAll(t *testing.T, src string) []planted {
	t.Helper()
	mutants, err := Plant([]byte(src), nil)
	if err != nil {
		t.Fatalf("Plant: %v", err)
	}
	var got []planted
	for _, m := range mutants {
		got = append(got, planted{src[m.Start:m.End], m.Replacement, m.Mutator})
	}
	return got
}

func TestPlant_EachKindOfBug(t *testing.T) {
	cases := []struct {
		name string
		expr string
		want []planted
	}{
		{"less", "a < b", []planted{{"<", "<=", "EqualityOperator"}, {"<", ">=", "EqualityOperator"}}},
		{"less or equal", "a <= b", []planted{{"<=", "<", "EqualityOperator"}, {"<=", ">", "EqualityOperator"}}},
		{"greater", "a > b", []planted{{">", ">=", "EqualityOperator"}, {">", "<=", "EqualityOperator"}}},
		{"greater or equal", "a >= b", []planted{{">=", ">", "EqualityOperator"}, {">=", "<", "EqualityOperator"}}},
		{"equal", "a == b", []planted{{"==", "!=", "EqualityOperator"}}},
		{"not equal", "a != b", []planted{{"!=", "==", "EqualityOperator"}}},
		{"plus", "a + b", []planted{{"+", "-", "ArithmeticOperator"}}},
		{"minus", "a - b", []planted{{"-", "+", "ArithmeticOperator"}}},
		{"times", "a * b", []planted{{"*", "/", "ArithmeticOperator"}}},
		{"divide", "a / b", []planted{{"/", "*", "ArithmeticOperator"}}},
		{"remainder", "a % b", []planted{{"%", "*", "ArithmeticOperator"}}},
		{"and", "p && q", []planted{{"&&", "||", "LogicalOperator"}}},
		{"or", "p || q", []planted{{"||", "&&", "LogicalOperator"}}},
		{"true", "true", []planted{{"true", "false", "BooleanLiteral"}}},
		{"false", "false", []planted{{"false", "true", "BooleanLiteral"}}},
		{"not", "!p", []planted{{"!", "", "BooleanLiteral"}}},
	}
	for _, c := range cases {
		t.Run(c.name, func(t *testing.T) {
			src := "package p\n\nfunc f(a, b int, p, q bool) any {\n\treturn " + c.expr + "\n}\n"
			got := plantAll(t, src)
			if !slices.Equal(got, c.want) {
				t.Errorf("Plant(%q) = %v, want %v", c.expr, got, c.want)
			}
		})
	}
}

func TestPlant_StatementsThatChangeAVariable(t *testing.T) {
	src := "package p\n\nfunc f(i int) {\n\ti++\n\ti--\n\ti += 2\n\ti -= 2\n\ti *= 2\n\ti /= 2\n}\n"
	want := []planted{
		{"++", "--", "UpdateOperator"},
		{"--", "++", "UpdateOperator"},
		{"+=", "-=", "AssignmentOperator"},
		{"-=", "+=", "AssignmentOperator"},
		{"*=", "/=", "AssignmentOperator"},
		{"/=", "*=", "AssignmentOperator"},
	}
	if got := plantAll(t, src); !slices.Equal(got, want) {
		t.Errorf("got %v, want %v", got, want)
	}
}

// A for loop's last clause counting the other way usually never ends, so
// the tests hang. No bug is planted there, but one is on a ++ or -- in the
// loop's body.
func TestPlant_LeavesAForLoopsLastClauseAlone(t *testing.T) {
	src := "package p\n\nfunc f(n int) (c int) {\n\tfor i := 0; i < n; i++ {\n\t\tc++\n\t}\n\tfor j := n; j > 0; j-- {\n\t\tc--\n\t}\n\treturn c\n}\n"
	want := []planted{
		{"<", "<=", "EqualityOperator"},
		{"<", ">=", "EqualityOperator"},
		{"++", "--", "UpdateOperator"},
		{">", ">=", "EqualityOperator"},
		{">", "<=", "EqualityOperator"},
		{"--", "++", "UpdateOperator"},
	}
	if got := plantAll(t, src); !slices.Equal(got, want) {
		t.Errorf("got %v, want %v", got, want)
	}
}


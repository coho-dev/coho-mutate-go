func TestMutantApply(t *testing.T) {
	src := []byte("package p\n\nfunc f(a, b int) bool { return !(a < b) }\n")
	mutants, err := Plant(src, nil)
	if err != nil {
		t.Fatal(err)
	}
	var got []string
	for _, m := range mutants {
		got = append(got, string(m.Apply(src)))
	}
	want := []string{
		"package p\n\nfunc f(a, b int) bool { return (a < b) }\n",
		"package p\n\nfunc f(a, b int) bool { return !(a <= b) }\n",
		"package p\n\nfunc f(a, b int) bool { return !(a >= b) }\n",
	}
	if strings.Join(got, "|") != strings.Join(want, "|") {
		t.Errorf("Apply gave\n%q\nwant\n%q", got, want)
	}
	if string(src) != "package p\n\nfunc f(a, b int) bool { return !(a < b) }\n" {
		t.Errorf("Apply changed the source it was given: %q", src)
	}
}

const markedLoop = `package p

func count(n int) int {
	c := 0
	for i := 0; i < n; {
		c++
		//mutate:ignore UpdateOperator: counting i down never ends
		i++
	}
	return c
}
`

// A marker skips the kinds of bug it names on the line after it, and only
// those. The bug keeps its place, with the marker's reason.
func TestPlant_AMarkerIgnoresTheKindsItNamesOnTheNextLine(t *testing.T) {
	mutants, err := Plant([]byte(markedLoop), nil)
	if err != nil {
		t.Fatal(err)
	}
	var got []string
	for _, m := range mutants {
		got = append(got, markedLoop[m.Start:m.End]+" "+m.Replacement+" "+m.Ignored)
	}
	want := []string{
		"< <= ",
		"< >= ",
		"++ -- ",
		"++ -- counting i down never ends",
	}
	if !slices.Equal(got, want) {
		t.Errorf("got %q, want %q", got, want)
	}
}

func TestPlant_AMarkerCanNameSeveralKinds(t *testing.T) {
	src := "package p\n\nfunc f(i, n int) bool {\n\t//mutate:ignore UpdateOperator, EqualityOperator: both stay as they are\n\tif i++; i < n {\n\t\treturn true\n\t}\n\treturn false\n}\n"
	mutants, err := Plant([]byte(src), nil)
	if err != nil {
		t.Fatal(err)
	}
	ignored := 0
	for _, m := range mutants {
		if m.Ignored != "" {
			ignored++
		}
	}
	if ignored != 3 {
		t.Errorf("%d bugs ignored, want 3: both for <, and the one for i++", ignored)
	}
}

// A marker above a for loop once skipped the bug on the loop's last clause.
// No bug is planted there now, so the marker is refused, saying why and that
// it can go.
func TestPlant_RefusesAMarkerForALoopsLastClause(t *testing.T) {
	src := "package p\n\nfunc f(n int) (c int) {\n\t//mutate:ignore UpdateOperator: counting i down never ends\n\tfor i := 0; i < n; i++ {\n\t\tc += i\n\t}\n\treturn c\n}\n"
	_, err := Plant([]byte(src), nil)
	if err == nil {
		t.Fatal("Plant accepted a marker with nothing to skip")
	}
	for _, want := range []string{"line 4", "no longer planted on a for loop's last clause", "delete this marker"} {
		if !strings.Contains(err.Error(), want) {
			t.Errorf("Plant = %v, want it to say %q", err, want)
		}
	}
}

// A marker that cannot be read, or that ignores nothing, would hide a bug
// or rot unseen, so it is refused, naming its line.
func TestPlant_RefusesAMarkerItCannotUse(t *testing.T) {
	for _, c := range []struct {
		name, marker, says string
	}{
		{"no reason", "//mutate:ignore UpdateOperator", "no reason"},
		{"an empty reason", "//mutate:ignore UpdateOperator:   ", "no reason"},
		{"no kind", "//mutate:ignore : counting down never ends", "no kind"},
		{"an unknown kind", "//mutate:ignore UpdateOperator, UpdateOperater: counting down never ends", "UpdateOperater is no kind"},
		{"a kind not on the next line", "//mutate:ignore LogicalOperator: there is no && here", "no LogicalOperator bug"},
		{"one of its kinds not on the next line", "//mutate:ignore UpdateOperator, LogicalOperator: there is no && here", "no LogicalOperator bug"},
	} {
		t.Run(c.name, func(t *testing.T) {
			src := strings.Replace(markedLoop, "//mutate:ignore UpdateOperator: counting i down never ends", c.marker, 1)
			_, err := Plant([]byte(src), nil)
			if err == nil || !strings.Contains(err.Error(), "line 7") || !strings.Contains(err.Error(), c.says) {
				t.Errorf("Plant = %v, want a refusal naming line 7 and saying %q", err, c.says)
			}
		})
	}
}

// counterIn is a function holding a counter c and the code that uses it.
func counterIn(body string) string {
	return "package p\n\nfunc f(xs []int) bool {\n" + body + "}\n"
}

// updates is the UpdateOperator bugs planted in src.
func updates(t *testing.T, src string) []planted {
	t.Helper()
	var got []planted
	for _, p := range plantAll(t, src) {
		if p.mutator == updateOperator {
			got = append(got, p)
		}
	}
	return got
}

// A counter that starts at 0, moves one way and is only compared with zero
// gives -1 where it gave 1 when it counts the other way, and both are
// non-zero, so no test could see that bug.
func TestPlant_LeavesACounterOnlyComparedWithZeroAlone(t *testing.T) {
	for _, c := range []struct{ name, body string }{
		{"declared with :=, compared with ==", "\tc := 0\n\tfor range xs {\n\t\tc++\n\t}\n\treturn c == 0\n"},
		{"declared with var, compared with !=", "\tvar c int\n\tfor range xs {\n\t\tc++\n\t}\n\treturn c != 0\n"},
		{"declared with var and 0", "\tvar c = 0\n\tfor range xs {\n\t\tc++\n\t}\n\treturn c != 0\n"},
		{"counting down, zero on the left", "\tc := 0\n\tfor range xs {\n\t\tc--\n\t}\n\treturn 0 == c\n"},
		{"compared in parentheses, more than once", "\tc := 0\n\tc++\n\tc++\n\tif (c) == 0 {\n\t\treturn false\n\t}\n\treturn c != 0\n"},
		{"never read", "\tc := 0\n\tc++\n\treturn true\n"},
		{"changed in a closure", "\tc := 0\n\tfunc() { c++ }()\n\treturn c == 0\n"},
	} {
		t.Run(c.name, func(t *testing.T) {
			if got := updates(t, counterIn(c.body)); len(got) != 0 {
				t.Errorf("got %v, want no UpdateOperator bug", got)
			}
		})
	}
}

// A counter that fails any one of the rules keeps its bug.
func TestPlant_KeepsTheBugOnAnyOtherCounter(t *testing.T) {
	for _, c := range []struct {
		name, body string
		want       int
	}{
		{"assigned to another variable", "\tc := 0\n\tc++\n\t_ = c\n\treturn true\n", 1},
		{"passed to a function", "\tc := 0\n\tc++\n\tprintln(c)\n\treturn true\n", 1},
		{"compared with <", "\tc := 0\n\tc++\n\treturn c < 1\n", 1},
		{"compared with a number other than zero", "\tc := 0\n\tc++\n\treturn c == 1\n", 1},
		{"starting at another value", "\tc := 1\n\tc++\n\treturn c == 0\n", 1},
		{"changed both ways", "\tc := 0\n\tc++\n\tc--\n\treturn c == 0\n", 2},
		{"changed by another assignment", "\tc := 0\n\tc++\n\tc += 2\n\treturn c == 0\n", 1},
		{"set again", "\tc := 0\n\tc++\n\tc = 0\n\treturn c == 0\n", 1},
		{"with its address taken", "\tc := 0\n\tc++\n\tp := &c\n\t_ = p\n\treturn c == 0\n", 1},
		{"declared twice", "\tc := 0\n\tc++\n\tif true {\n\t\tc := 5\n\t\t_ = c\n\t}\n\treturn c == 0\n", 1},
		{"declared by a range clause", "\tfor c := range xs {\n\t\tc++\n\t\t_ = c == 0\n\t}\n\treturn true\n", 1},
	} {
		t.Run(c.name, func(t *testing.T) {
			if got := updates(t, counterIn(c.body)); len(got) != c.want {
				t.Errorf("got %v, want %d UpdateOperator bugs, one on each ++ and --", got, c.want)
			}
		})
	}
	t.Run("returned", func(t *testing.T) {
		src := "package p\n\nfunc f() int {\n\tc := 0\n\tc++\n\treturn c\n}\n"
		if got := updates(t, src); len(got) != 1 {
			t.Errorf("got %v, want the one UpdateOperator bug", got)
		}
	})
	t.Run("a struct field", func(t *testing.T) {
		src := "package p\n\ntype s struct{ c int }\n\nfunc f(v s) bool {\n\tv.c++\n\treturn v.c == 0\n}\n"
		if got := updates(t, src); len(got) != 1 {
			t.Errorf("got %v, want the one UpdateOperator bug", got)
		}
	})
	t.Run("a parameter, and a counter of its name in a block", func(t *testing.T) {
		src := "package p\n\nfunc f(c int, ok bool) bool {\n\tif ok {\n\t\tc := 0\n\t\tc++\n\t\treturn c == 0\n\t}\n\tc++\n\treturn c == 0\n}\n"
		if got := updates(t, src); len(got) != 2 {
			t.Errorf("got %v, want both UpdateOperator bugs", got)
		}
	})
	t.Run("a package-level variable stepped outside the counter's block", func(t *testing.T) {
		src := "package p\n\nvar c int\n\nfunc f(ok bool) bool {\n\tc++\n\tif ok {\n\t\tc := 0\n\t\tc++\n\t\treturn c == 0\n\t}\n\treturn c == 0\n}\n"
		if got := updates(t, src); len(got) != 2 {
			t.Errorf("got %v, want both UpdateOperator bugs", got)
		}
	})
	t.Run("the same name in another function", func(t *testing.T) {
		src := counterIn("\tc := 0\n\tc++\n\treturn c == 0\n") + "\nfunc g(c int) int {\n\tc++\n\treturn c\n}\n"
		if got := updates(t, src); len(got) != 1 {
			t.Errorf("got %v, want g's one UpdateOperator bug", got)
		}
	})
}


const testOnlySrc = `package p

func keep(a int) bool { return a > 0 }

func (s *store) fixture(a int) bool { return a == 1 }

func helper(a int) bool {
	//mutate:ignore EqualityOperator: a fixture
	return a != 2
}

type store struct{}
`

// A function only test files call gets no bug, and a marker in it is
// refused, saying why.
func TestPlant_PlantsNothingInAFunctionOnlyTestsCall(t *testing.T) {
	only := map[funcName]bool{{"store", "fixture"}: true}
	mutants, err := Plant([]byte(strings.Replace(testOnlySrc, "\t//mutate:ignore EqualityOperator: a fixture\n", "", 1)), only)
	if err != nil {
		t.Fatal(err)
	}
	var got []string
	for _, m := range mutants {
		got = append(got, m.Replacement)
	}
	if want := []string{">=", "<=", "=="}; !slices.Equal(got, want) {
		t.Errorf("got bugs %q, want %q: keep's and helper's, and none of fixture's", got, want)
	}

	only[funcName{"", "helper"}] = true
	_, err = Plant([]byte(testOnlySrc), only)
	if err == nil {
		t.Fatal("Plant accepted a marker in a function only tests call")
	}
	for _, want := range []string{"line 8:", "no longer planted on a line of a function only test files call", "delete this marker"} {
		if !strings.Contains(err.Error(), want) {
			t.Errorf("Plant = %v, want it to say %q", err, want)
		}
	}
}

func TestPlant_ComesBackInSourceOrder(t *testing.T) {
	src := "package p\n\nfunc f(a, b int) bool {\n\treturn a+b == 3 && !(a > b)\n}\n"
	mutants, err := Plant([]byte(src), nil)
	if err != nil {
		t.Fatal(err)
	}
	for i := 1; i < len(mutants); i++ {
		if mutants[i].Start < mutants[i-1].Start {
			t.Fatalf("mutant %d starts at %d, before mutant %d at %d", i, mutants[i].Start, i-1, mutants[i-1].Start)
		}
	}
	if len(mutants) != 6 {
		t.Errorf("got %d mutants, want 6 (+, ==, &&, !, and two for >)", len(mutants))
	}
}

